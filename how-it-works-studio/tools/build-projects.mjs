#!/usr/bin/env node
'use strict';

/**
 * build-projects.mjs - generate the derived documents for every episode.
 *
 * Source of truth:   content/csv/*.csv   (hand-authored)
 * Generated:         projects/<slug>/script.md
 *                    projects/<slug>/storyboard.md
 *                    projects/<slug>/publishing.md
 *
 * Hand-authored (never overwritten by this script): projects/<slug>/README.md
 *
 * The viseme strips in storyboard.md are produced by the real lip-sync engine
 * (src/stage/rig/visemes.js + lipsync.js), so the storyboard cannot drift from
 * what the renderer will do.
 *
 * Usage: node tools/build-projects.mjs [--only 0103]
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const Visemes = require('../src/stage/rig/visemes.js');
const LipSync = require('../src/stage/rig/lipsync.js');

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CSV = path.join(ROOT, 'content', 'csv');
const FPS = 30;

// ---------------------------------------------------------------------------
// csv (RFC 4180 enough for our own files)
// ---------------------------------------------------------------------------

function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (ch === '"') {
        quoted = false;
      } else {
        field += ch;
      }
    } else if (ch === '"') {
      quoted = true;
    } else if (ch === ',') {
      row.push(field);
      field = '';
    } else if (ch === '\n') {
      row.push(field);
      rows.push(row);
      row = [];
      field = '';
    } else if (ch !== '\r') {
      field += ch;
    }
  }
  if (field.length || row.length) {
    row.push(field);
    rows.push(row);
  }
  const header = rows.shift();
  return rows
    .filter((r) => r.some((c) => c !== ''))
    .map((r) => {
      const obj = {};
      header.forEach((key, i) => {
        obj[key] = (r[i] || '').trim();
      });
      return obj;
    });
}

const readTab = (name) => parseCsv(fs.readFileSync(path.join(CSV, `${name}.csv`), 'utf8'));
const episodeId = (row) => row.episode_id.replace(/^'/, '');
const list = (cell) =>
  String(cell || '')
    .split(';')
    .map((s) => s.trim())
    .filter(Boolean);

const seconds = (v) => Number(v);
const mmss = (s) => `${Math.floor(s / 60)}:${String(Math.round(s % 60)).padStart(2, '0')}`;
const timecode = (frames) => {
  const total = frames / FPS;
  return `${mmss(total)}.${String(Math.round((total % 1) * 10))}`;
};

// ---------------------------------------------------------------------------
// per-episode model
// ---------------------------------------------------------------------------

function buildModel(ep) {
  const id = episodeId(ep);
  const beats = readTab('beats')
    .filter((b) => episodeId(b) === id)
    .sort((a, b) => Number(a.beat_no) - Number(b.beat_no));
  const sources = readTab('sources').filter((s) => episodeId(s) === id);
  const publish = readTab('publish').find((p) => episodeId(p) === id);
  const props = readTab('props').filter((p) => episodeId(p) === id);
  const character = readTab('character').filter((c) => episodeId(c) === id);

  let cursor = 0;
  const scheduled = beats.map((b) => {
    const frames = Math.round(seconds(b.duration_s) * FPS);
    const scene = { ...b, startFrame: cursor, durationFrames: frames, startSeconds: cursor / FPS };
    cursor += frames;
    return scene;
  });

  return {
    ep,
    id,
    slug: ep.slug,
    beats: scheduled,
    sources,
    publish,
    props,
    character,
    totalFrames: cursor,
    totalSeconds: cursor / FPS,
    words: beats.reduce((n, b) => n + b.narration.split(/\s+/).filter(Boolean).length, 0),
  };
}

// ---------------------------------------------------------------------------
// script.md
// ---------------------------------------------------------------------------

function renderScript(model) {
  const { ep, id, beats, sources, totalSeconds, totalFrames, words } = model;
  const lines = [];

  lines.push(`# ${id} — ${ep.title}`);
  lines.push('');
  lines.push(`<!-- Generated by tools/build-projects.mjs from content/csv/. Do not edit by hand. -->`);
  lines.push('');
  lines.push('| | |');
  lines.push('| --- | --- |');
  lines.push(`| Episode | ${id} |`);
  lines.push(`| Slug | \`${ep.slug}\` |`);
  lines.push(`| Series | ${ep.series} |`);
  lines.push(`| Level | ${ep.level} |`);
  lines.push(`| Beats | ${beats.length} |`);
  lines.push(`| Length | ${totalSeconds.toFixed(1)} s — ${totalFrames} frames @ ${FPS} fps |`);
  lines.push(`| Words spoken | ${words} |`);
  lines.push(`| Status | \`${ep.status}\` |`);
  lines.push('');
  lines.push('## The question');
  lines.push('');
  lines.push(`> ${ep.question}`);
  lines.push('');
  lines.push('**The walkaway:**');
  lines.push('');
  lines.push(`> ${ep.answer_oneliner}`);
  lines.push('');

  lines.push('## Script');
  lines.push('');
  lines.push('| # | In | Type | s | Narration | Caption text (board) |');
  lines.push('| --- | --- | --- | --- | --- | --- |');
  for (const b of beats) {
    const board = b.on_screen_text ? b.on_screen_text : '—';
    lines.push(
      `| ${b.beat_no} | ${timecode(b.startFrame)} | ${b.beat_type} | ${Number(b.duration_s).toFixed(1)} | ${b.narration} | ${board} |`
    );
  }
  lines.push('');

  lines.push('## Claims and sources');
  lines.push('');
  if (!sources.length) {
    lines.push('_No sources recorded. This episode makes no factual claims._');
  } else {
    lines.push('| Claim id | Beat | Claim | Source | Kind | Checked |');
    lines.push('| --- | --- | --- | --- | --- | --- |');
    for (const s of sources) {
      lines.push(
        `| ${s.claim_id} | ${s.beat_no} | ${s.claim} | [${s.source_title}](${s.source_url}) | ${s.kind} | ${s.checked} |`
      );
    }
    lines.push('');
    lines.push('Quotes are stored in the `Sources` tab: they are the sentence that supports the');
    lines.push('claim, kept so the claim can be re-checked after the page changes.');
  }
  lines.push('');

  lines.push('## Reading check');
  lines.push('');
  lines.push('Every caption needs `words / 4 + 0.6` seconds on screen. Measured per beat:');
  lines.push('');
  lines.push('| # | Words | Needed (s) | Actual (s) | Verdict |');
  lines.push('| --- | --- | --- | --- | --- |');
  for (const b of beats) {
    const w = b.narration.split(/\s+/).filter(Boolean).length;
    const needed = w / 4 + 0.6;
    const actual = seconds(b.duration_s);
    lines.push(
      `| ${b.beat_no} | ${w} | ${needed.toFixed(1)} | ${actual.toFixed(1)} | ${actual >= needed ? 'ok' : '**too fast**'} |`
    );
  }
  lines.push('');
  return lines.join('\n');
}

// ---------------------------------------------------------------------------
// storyboard.md
// ---------------------------------------------------------------------------

function visemeStrip(text, frames) {
  const schedule = LipSync.buildSchedule(text, frames, { mode: 'full-body' });
  const cells = schedule.frames.map((entry) => `${entry.v}@${entry.f}`).join(' · ');
  return { cells, count: schedule.frames.length, schedule };
}

function renderStoryboard(model) {
  const { ep, id, beats, props } = model;
  const lines = [];
  lines.push(`# ${id} — Storyboard`);
  lines.push('');
  lines.push(`<!-- Generated by tools/build-projects.mjs. Viseme strips come from the real`);
  lines.push(`     lip-sync engine, so this file cannot drift from the renderer. -->`);
  lines.push('');
  lines.push(`Character: **Nao**, outfit \`casual\`, full-body framing in the \`presenter\` zone.`);
  lines.push(`Lip-sync mode: \`full-body\` (three mouth states) unless the beat names a close shot.`);
  lines.push('');

  for (const b of beats) {
    lines.push(`## Beat ${b.beat_no} — ${b.beat_type} · ${Number(b.duration_s).toFixed(1)} s · ${timecode(b.startFrame)}`);
    lines.push('');
    lines.push(`- **Narration:** ${b.narration}`);
    if (b.on_screen_text) lines.push(`- **Board title:** ${b.on_screen_text}`);
    const items = list(b.board_items);
    if (items.length) lines.push(`- **Board items:** ${items.join(' → ')}`);
    const onStage = list(b.props);
    lines.push(
      `- **World:** ${onStage.length ? onStage.join(', ') : 'no props (clean stage)'} · camera \`${b.camera || 'default'}\``
    );
    lines.push(
      `- **Nao:** gesture \`${b.gesture || 'talk-hands'}\` · expression \`${b.expression || 'neutral'}\``
    );
    lines.push(`- **Transition in:** ${b.transition || 'fade'} · **sfx:** ${b.sfx || 'none'}`);
    if (list(b.emphasis).length) lines.push(`- **Emphasis:** ${list(b.emphasis).join(', ')}`);
    if (b.note) lines.push(`- **Note:** ${b.note}`);

    const strip = visemeStrip(b.narration, b.durationFrames);
    lines.push('');
    lines.push(`<details><summary>Mouth schedule (${strip.count} change points)</summary>`);
    lines.push('');
    lines.push('```');
    lines.push(strip.cells);
    lines.push('```');
    lines.push('');
    lines.push('</details>');
    lines.push('');
  }

  if (props.length) {
    lines.push('## Props used');
    lines.push('');
    lines.push('| Prop | First beat | Slot | Label | Family |');
    lines.push('| --- | --- | --- | --- | --- |');
    for (const p of props) {
      lines.push(`| ${p.prop_id} | ${p.first_beat} | ${p.slot} | ${p.label} | ${p.family} |`);
    }
    lines.push('');
  }

  if (model.character.length) {
    lines.push('## Character cues (mid-beat changes)');
    lines.push('');
    lines.push('| Beat | At (s) | Pose | Gesture | Expression | Blend |');
    lines.push('| --- | --- | --- | --- | --- | --- |');
    for (const c of model.character) {
      lines.push(`| ${c.beat_no} | ${c.at_s} | ${c.pose} | ${c.gesture} | ${c.expression} | ${c.blend_s}s |`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

// ---------------------------------------------------------------------------
// publishing.md
// ---------------------------------------------------------------------------

function renderPublishing(model) {
  const { ep, id, publish, sources } = model;
  if (!publish) return null;
  const tags = list(publish.hashtags).map((t) => `#${t.replace(/^#/, '')}`);
  const lines = [];
  lines.push(`# Publishing — ${id} ${ep.title}`);
  lines.push('');
  lines.push(`<!-- Generated by tools/build-projects.mjs from the Publish and Sources tabs. -->`);
  lines.push('');
  lines.push('## Title');
  lines.push('');
  lines.push(publish.cover_text || ep.title);
  lines.push('');
  lines.push('## Caption (Instagram)');
  lines.push('');
  lines.push('```');
  lines.push(publish.caption);
  lines.push('```');
  lines.push('');
  lines.push(`Length: ${publish.caption.length} characters.`);
  lines.push('');
  lines.push('## YouTube Shorts');
  lines.push('');
  lines.push(`**Title:** ${publish.yt_title || ep.title}`);
  lines.push('');
  lines.push('**Description:**');
  lines.push('');
  lines.push('```');
  lines.push(publish.caption);
  lines.push('');
  lines.push(sources.length ? 'Sources:' : '');
  sources.forEach((s) => {
    lines.push(`- ${s.claim} (${s.source_title}) ${s.source_url} checked ${s.checked}`);
  });
  lines.push('```');
  lines.push('');
  lines.push('## Hashtags');
  lines.push('');
  lines.push(tags.join(' '));
  lines.push('');
  lines.push('## Cover');
  lines.push('');
  lines.push(`- **Frame:** ${publish.cover_frame}`);
  lines.push(`- **Text:** ${publish.cover_text}`);
  lines.push(`- **Series tag:** #${publish.series_tag}`);
  lines.push('');
  lines.push('## Disclosure');
  lines.push('');
  lines.push(publish.disclosure);
  lines.push('');
  lines.push('## Sources (list these in the post)');
  lines.push('');
  sources.forEach((s) => {
    lines.push(`- **${s.claim}** — [${s.source_title}](${s.source_url}) — checked ${s.checked} (${s.kind})`);
  });
  if (!sources.length) lines.push('_None._');
  lines.push('');
  if (publish.tool_list) {
    lines.push('## Tool list (kept here, not in the video, so it can be updated without a re-render)');
    lines.push('');
    lines.push(publish.tool_list);
    lines.push('');
  }
  lines.push('## Before posting');
  lines.push('');
  lines.push('- [ ] `npm run verify` passes for this episode.');
  lines.push('- [ ] Caption reads correctly without the video.');
  lines.push('- [ ] Source links still resolve.');
  lines.push('- [ ] Watched once, muted, on a phone.');
  lines.push('- [ ] Posted by hand; `published_url` filled in the Publish tab.');
  lines.push('');
  return lines.join('\n');
}

// ---------------------------------------------------------------------------
// main
// ---------------------------------------------------------------------------

const onlyArg = process.argv.indexOf('--only');
const only = onlyArg !== -1 ? process.argv[onlyArg + 1] : null;

const episodes = readTab('episodes').filter((ep) => !only || episodeId(ep) === only);
let written = 0;

for (const ep of episodes) {
  const model = buildModel(ep);
  const dir = path.join(ROOT, 'projects', model.slug);
  fs.mkdirSync(dir, { recursive: true });

  fs.writeFileSync(path.join(dir, 'script.md'), renderScript(model));
  fs.writeFileSync(path.join(dir, 'storyboard.md'), renderStoryboard(model));
  const publishing = renderPublishing(model);
  if (publishing) fs.writeFileSync(path.join(dir, 'publishing.md'), publishing);

  written++;
  console.log(
    `${model.id}  ${String(model.beats.length).padStart(2)} beats  ` +
      `${model.totalSeconds.toFixed(1)}s  ${model.totalFrames} frames  → projects/${model.slug}/`
  );
}

console.log(`\n${written} episode(s) written. README.md files are hand-authored and left alone.`);
